'use strict';
const assert=require('node:assert/strict');
const {harness,minimal}=require('./helpers/core-harness');
const {s}=harness(['clone-core','kernel-core','transaction-core','authorization-core','document-proof-core','save-schema']);
const state=minimal();state.profile={name:'Global Holdings',founder:'Founder'};
const document={id:'B342-PAYABLE',number:'B342-PAYABLE',company:'group',counterparty:'Supplier',amount:125,subtotal:125,tax:0,total:125,status:'open'};
s.GH_DOCUMENT_PROOF.sealDocument(state,document,{type:'invoice-payable',companyId:'group'});
state.finance.invoices.push(document);
const firstId=document.documentProofId;
s.GH_DOCUMENT_PROOF.amendDocument(state,document,{transition:'invoice-payable-settled',mutate:row=>{row.status='settled';row.settledAt=10;}});
assert.notEqual(document.documentProofId,firstId);
const liveState=s.GH_TRANSACTION_CORE.enableKernelOwner(state);
let result=s.GH_SAVE_SCHEMA.validate(liveState,{lockVerifiedProofs:true});
assert.equal(result.ok,true,`full validation must pass before any record can enter the cache: ${result.errors}`);
result=s.GH_SAVE_SCHEMA.validate(liveState,{lockVerifiedProofs:true});
assert.equal(result.ok,true);
const metrics=s.GH_SAVE_SCHEMA.telemetry().lastValidation;
assert.equal(metrics.proofStateCacheHits,1,'repeated live-state validation must reuse its revision-keyed proof result');
assert.equal(s.GH_TRANSACTION_CORE.kernelOwnerStatus(liveState).enabled,true);

const previous=s.GH_CLONE_CORE.clone(liveState.documentProofs.recordsById[firstId]);
liveState.documentProofs.recordsById[firstId]={...previous,contentDigest:'f'.repeat(64)};
result=s.GH_SAVE_SCHEMA.validate(liveState,{lockVerifiedProofs:true});
assert.equal(result.ok,false,'changing the predecessor must invalidate the chained cache');
assert.ok(result.errors.includes('document-proof-record-integrity'),'the verifier must reject a replaced predecessor');
assert.equal(s.GH_SAVE_SCHEMA.telemetry().lastValidation.proofStateCacheHits,0,'a changed kernel proof root must miss the prior state cache');
liveState.documentProofs.recordsById[firstId]=previous;
result=s.GH_SAVE_SCHEMA.validate(liveState,{lockVerifiedProofs:true});
assert.equal(result.ok,true,`restored proof record must validate again: ${result.errors}`);
assert.equal(s.GH_SAVE_SCHEMA.telemetry().lastValidation.proofStateCacheHits,0,'restoring content through a new transaction still requires a fresh verification');

const liveDocument=liveState.finance.invoices[0],signedCounterparty=liveDocument.counterparty;
liveDocument.counterparty='Tampered after signing';
result=s.GH_SAVE_SCHEMA.validate(liveState,{lockVerifiedProofs:true});
assert.equal(result.ok,false,'a finance-root revision must invalidate the proof result for signed documents');
assert.ok(result.errors.includes('document-proof-integrity'));
assert.equal(s.GH_SAVE_SCHEMA.telemetry().lastValidation.proofStateCacheHits,0);
liveDocument.counterparty=signedCounterparty;
assert.equal(s.GH_SAVE_SCHEMA.validate(liveState,{lockVerifiedProofs:true}).ok,true);

liveState.simSeconds=-1;
result=s.GH_SAVE_SCHEMA.validate(liveState,{lockVerifiedProofs:true});
assert.equal(result.ok,false,'non-proof schema checks must still run on proof-cache hits');
assert.ok(result.errors.includes('sim-seconds'));
assert.equal(s.GH_SAVE_SCHEMA.telemetry().lastValidation.proofStateCacheHits,1,'unrelated state edits do not repeat unchanged proof verification');
liveState.simSeconds=0;
assert.equal(s.GH_SAVE_SCHEMA.validate(liveState,{lockVerifiedProofs:true}).ok,true);
assert.equal(s.GH_SAVE_SCHEMA.SAVE_SCHEMA_VERSION,'2.0.0');
console.log('Build342 document proof cache: live kernel proxy, revision-keyed reuse, tamper invalidation, Save Schema 2.0.0 PASS');
