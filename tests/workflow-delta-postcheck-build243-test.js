'use strict';
const assert=require('assert'),path=require('path');
const ROOT=path.resolve(__dirname,'..');
let issues=[{id:'OLD_WARNING',severity:'warning',domain:'energy'}];
globalThis.GH_INTEGRITY_CORE={check:()=>({status:issues.some(x=>x.severity==='critical')?'critical':issues.length?'warning':'healthy',counts:{critical:issues.filter(x=>x.severity==='critical').length,warning:issues.filter(x=>x.severity==='warning').length,total:issues.length},issues})};
globalThis.GH_EVENT_LEDGER={append:()=>({})};
globalThis.GH_DIAGNOSTICS={record:()=>({})};
const WF=require(path.join(ROOT,'WebApp','workflow-core.js'));
const state={simSeconds:0};
let before=globalThis.GH_INTEGRITY_CORE.check(state);
let out=WF.postCheck(state,{action:'noop',beforeIssues:before.issues});
assert.equal(out.status,'healthy','pre-existing warning must not color an unrelated command');
issues=[...issues,{id:'NEW_WARNING',severity:'warning',domain:'finance'}];
out=WF.postCheck(state,{action:'changed',beforeIssues:before.issues});
assert.equal(out.status,'warning','new warning must be reported');
assert.equal(out.newIssues.length,1);assert.equal(out.newIssues[0].id,'NEW_WARNING');
issues=[{id:'CRIT',severity:'critical',domain:'save'}];
out=WF.postCheck(state,{action:'critical',beforeIssues:issues});
assert.equal(out.ok,false,'critical state remains blocking even if pre-existing');
console.log('workflow-delta-postcheck-build243-test: PASS');
