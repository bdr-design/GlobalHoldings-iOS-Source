'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {harness,minimal,ROOT}=require('./helpers/core-harness');
const {s}=harness(['save-schema','authorization-core','document-proof-core','transaction-core','domain-command-core','finance-core']);
const state=minimal();state.profile={name:'Build336 Proof Pressure',founder:'Founder'};s.GH_FINANCE_CORE.ensure(state);
const F=s.GH_FINANCE_CORE,P=s.GH_DOCUMENT_PROOF,S=s.GH_SAVE_SCHEMA;
for(let i=0;i<1220;i++)F.execute({state},'founder-investment',{company:'group',amount:100+(i%7),ref:`FND-P-${String(i).padStart(5,'0')}`});
assert.equal(state.finance.transfers.length,1220);
assert.equal(state.companyFinance.group.ledger.length,1220);
assert.equal(Object.keys(state.documentProofs.recordsById).length,1220);
assert.equal(state.companyFinance.group.ledger.some(row=>row.documentProofId),false,'new ledger rows must be projections before pressure compaction');
assert.equal(S.validate(state).ok,true,'pressure fixture must start schema-valid');
const beforeBytes=Buffer.byteLength(JSON.stringify(state));

const app=fs.readFileSync(path.join(ROOT,'WebApp/app.js'),'utf8'),start=app.indexOf('  function financeAuditArchive()'),end=app.indexOf('  function normalizeSimulationClocks()',start);
assert.ok(start>=0&&end>start,'compaction owner block must be present');
Object.assign(s,{state,clone:v=>v===undefined?undefined:JSON.parse(JSON.stringify(v)),companyFinanceTypes:()=>Object.keys(state.companyFinance),companyBook:t=>state.companyFinance[t]});
vm.runInContext(app.slice(start,end)+'\nglobalThis.__compact=compactSimulationState;',s,{filename:'app-compaction-pressure.js'});
state.simSeconds=298800;s.__compact(true);
assert.equal(state.finance.transfers.length,1200,'bounded transfer hot set must remain');
assert.equal(state.finance.auditArchive.records.transfers.length,20,'overflow canonical transfers must archive in full');
assert.equal(state.companyFinance.group.ledger.length,0,'day-0 ledger projections should aggregate at day-3 cutoff');
assert.ok(state.finance.auditArchive.digests.some(row=>row.kind==='companyLedger-group'),'company ledger aggregate must exist');
assert.equal(S.validate(state).ok,true,'schema must remain valid after full-proof archive and ledger aggregation');
const afterBytes=Buffer.byteLength(JSON.stringify(state));
const topStateBytes=Object.entries(state).map(([key,value])=>({key,bytes:Buffer.byteLength(JSON.stringify(value))})).sort((a,b)=>b.bytes-a.bytes).slice(0,12);
const forensic=P.forensicInspectStateProofs(state);
assert.equal(forensic.ok,true,JSON.stringify(forensic.documentFailures.slice(0,3)));
for(const row of state.finance.auditArchive.records.transfers)assert.equal(P.verifyDocument(state,row).ok,true,'every archived legal transfer must remain cryptographically verifiable');
console.log(JSON.stringify({suite:'build336-real-proof-compaction-pressure',passed:true,beforeBytes,afterBytes,reductionPct:+((1-afterBytes/beforeBytes)*100).toFixed(2),topStateBytes,proofs:Object.keys(state.documentProofs.recordsById).length,liveTransfers:state.finance.transfers.length,archivedTransfers:state.finance.auditArchive.records.transfers.length,digests:state.finance.auditArchive.digests.length},null,2));
